function copyFatwaText(id) {
    const item = fatwaDatabase.find(f => f.id === id);
    if (!item) return;
    const text = `السؤال: ${item.question}\n\nالإجابة المختصرة: ${item.shortAnswer}\n\nالتفصيل: ${item.detail}`;
    navigator.clipboard.writeText(text).then(() => showFatwaToast('تم نسخ الفتوى بنجاح'));
}

function shareFatwaText(id) {
    const item = fatwaDatabase.find(f => f.id === id);
    if (!item) return;
    const text = `${item.question}\n\n${item.shortAnswer}`;
    if (navigator.share) {
        navigator.share({ title: 'فتوى شرعية', text }).catch(() => {});
    } else {
        navigator.clipboard.writeText(text).then(() => showFatwaToast('تم نسخ الفتوى للمشاركة'));
    }
}

